//! The generated C headers of a package build: each member's symbol names
//! (`pycc_ext_member.h`, read first by the member's own unit) and the
//! package unit's member table (`pycc_pkg_members.h`, read by
//! `src/ext/package/finder.c`).

use super::PackageModule;

/// The member table's file name, beside the package unit.
pub(crate) const MEMBERS_HEADER_NAME: &str = "pycc_pkg_members.h";

/// The names a member's C unit shares with its LLVM object -- what the
/// object defines that the unit uses (`fnptr_`/thunk names of the generated
/// companion `inc`, the module body, its frame records) and what the unit
/// defines for it (`pycc_codegen::MODULE_UNIT_ENTRIES`) -- each defined as
/// its prefixed name, and the member's definition entry point.
pub(crate) fn member_header(prefix: &str, inc: &str) -> String {
    let mut names: Vec<String> = pycc_codegen::MODULE_UNIT_ENTRIES
        .iter()
        .map(|name| name.to_string())
        .collect();
    names.extend(
        [
            pycc_codegen::EXT_MODULE_EXEC_SYMBOL,
            "pycc_fn_info_table",
            "pycc_fn_info_count",
            "pycc_ext_member_def",
        ]
        .map(str::to_string),
    );
    let mut generated: Vec<String> = Vec::new();
    for word in inc.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_')) {
        if (word.starts_with("fnptr_") || word.starts_with(pycc_codegen::EXT_THUNK_PREFIX))
            && !generated.iter().any(|seen| seen == word)
        {
            generated.push(word.to_string());
        }
    }
    names.extend(generated);
    let mut out = String::from(
        "/* Generated by pycc for a member of a package built whole (v0.8): the \
         names this\n * module's unit shares with its object, prefixed per module. */\n",
    );
    for name in names {
        out.push_str(&format!("#define {name} {prefix}{name}\n"));
    }
    out
}

/// The package unit's member table: the package's name and, sorted by
/// relative name (the package's own `__init__` first, as `""`), each
/// member's relative name, whether it is a package, and its definition's
/// entry point.
pub(crate) fn members_header(package: &str, modules: &[PackageModule]) -> String {
    let mut out = format!(
        "/* Generated by pycc: the compiled modules of package `{package}`. */\n\
         #define PYCC_PKG_NAME {package}\n#define PYCC_PKG_NAME_STR \"{package}\"\n\n"
    );
    for module in modules {
        out.push_str(&format!(
            "extern PyModuleDef *{}pycc_ext_member_def(void);\n",
            pycc_codegen::member_prefix(&module.dotted)
        ));
    }
    out.push_str("\nstatic const PyccPkgMember pycc_pkg_members[] = {\n");
    for module in modules {
        out.push_str(&format!(
            "    {{\"{}\", {}, {}pycc_ext_member_def}},\n",
            module.relative,
            i32::from(module.is_package),
            pycc_codegen::member_prefix(&module.dotted)
        ));
    }
    out.push_str("};\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_members_header_names_every_shared_symbol_with_its_prefix_once() {
        let inc = "extern void *fnptr_f;\n... fnptr_f ... pycc_ext_thunk_g(1);\n";
        let header = member_header("pycc_P1p1m_", inc);
        assert!(
            header.contains("#define fnptr_f pycc_P1p1m_fnptr_f\n"),
            "{header}"
        );
        assert_eq!(header.matches("#define fnptr_f ").count(), 1);
        assert!(header.contains("#define pycc_ext_thunk_g pycc_P1p1m_pycc_ext_thunk_g\n"));
        assert!(header.contains("#define pycc_ext_publish pycc_P1p1m_pycc_ext_publish\n"));
        assert!(header.contains("#define pycc_ext_module_exec pycc_P1p1m_pycc_ext_module_exec\n"));
    }

    #[test]
    fn the_member_table_lists_the_package_first_with_each_entry_point() {
        let module = |dotted: &str, relative: &str, is_package| PackageModule {
            dotted: dotted.to_string(),
            relative: relative.to_string(),
            path: Default::default(),
            is_package,
        };
        let header = members_header("p", &[module("p", "", true), module("p.m", "m", false)]);
        assert!(header.contains("#define PYCC_PKG_NAME p\n"), "{header}");
        assert!(
            header.contains("    {\"\", 1, pycc_P1p_pycc_ext_member_def},\n"),
            "{header}"
        );
        assert!(
            header.contains("    {\"m\", 0, pycc_P1p1m_pycc_ext_member_def},\n"),
            "{header}"
        );
    }
}
