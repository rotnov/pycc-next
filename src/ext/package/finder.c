/*
 * The package unit of a package built whole (v0.8): one extension,
 * `pkg/__init__.abi3.so` (`.pyd`), holds every compiled module of the
 * package, and this unit is its entry point.
 *
 * CPython imports the extension as the package itself and calls its one
 * `PyInit_<package>`. The package module's exec first puts this unit's
 * finder on `sys.meta_path` and then runs the package's own body (the
 * `__init__` member's exec slot). Each other compiled module of the package
 * keeps its own module object, created when it is imported -- lazily, in
 * import order, as CPython creates any module -- from its own definition:
 * the finder answers `find_spec` only for the names in its table (relative
 * to the package's name at run time, so a vendored copy works too),
 * `create_module` is `PyModule_FromDefAndSpec` and `exec_module` is
 * `PyModule_ExecDef`, the multi-phase initialization an extension module of
 * its own gets from `ExtensionFileLoader`. So `sys.modules`, circular
 * imports, `importlib.reload` (exec again) and `__spec__`, `__file__`,
 * `__loader__`, `__path__` behave as for any module. A module's `__file__`
 * is the path its own extension would have had (`pkg/sub/mod.abi3.so`),
 * inside the package's directory, which is what code finding its data next
 * to `__file__` needs.
 *
 * The member table (`pycc_pkg_members.h`) is generated by the build: the
 * package's name, and each member's name relative to the package, whether
 * it is a package, and its definition's entry point (each member's own
 * module unit, `module_init.c`).
 */

#define Py_LIMITED_API 0x030D0000
#include <Python.h>
#include <string.h>

typedef struct PyccPkgMember {
    /* The name below the package (`""` for the package itself, `sub.mod`). */
    const char *name;
    int is_package;
    PyModuleDef *(*def)(void);
} PyccPkgMember;

#include "pycc_pkg_members.h"

/* The directory separator of a module's `__file__`, as importlib's own. */
#if defined(_WIN32)
#define PYCC_PKG_SEP "\\"
#else
#define PYCC_PKG_SEP "/"
#endif

#define PYCC_PKG_MEMBER_COUNT ((Py_ssize_t)(sizeof(pycc_pkg_members) / sizeof(pycc_pkg_members[0])))

/* The finder (one per process: the package's extension is loaded once),
 * and what it computes names and paths from, set by the package's exec:
 * the package's name, its directory and the extension's file suffix. */
static PyObject *pycc_pkg_finder = NULL;
static PyObject *pycc_pkg_name = NULL;
static PyObject *pycc_pkg_dir = NULL;
static PyObject *pycc_pkg_suffix = NULL;

/* The member called `name` relative to the package, or NULL. The table is
 * sorted by name. */
static const PyccPkgMember *pycc_pkg_member(const char *name)
{
    Py_ssize_t lo = 0, hi = PYCC_PKG_MEMBER_COUNT;

    while (lo < hi) {
        Py_ssize_t mid = (lo + hi) / 2;
        int c = strcmp(pycc_pkg_members[mid].name, name);

        if (c == 0) {
            return &pycc_pkg_members[mid];
        }
        if (c < 0) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return NULL;
}

/* The member a full module name (`pkg.sub.mod`) names, or NULL for the
 * package itself and any name outside it. */
static const PyccPkgMember *pycc_pkg_lookup(PyObject *fullname)
{
    Py_ssize_t full_len, pkg_len;
    const char *full, *pkg;

    if (pycc_pkg_name == NULL || !PyUnicode_Check(fullname)) {
        return NULL;
    }
    full = PyUnicode_AsUTF8AndSize(fullname, &full_len);
    pkg = PyUnicode_AsUTF8AndSize(pycc_pkg_name, &pkg_len);
    if (full == NULL || pkg == NULL) {
        PyErr_Clear();
        return NULL;
    }
    if (full_len <= pkg_len + 1 || memcmp(full, pkg, (size_t)pkg_len) != 0
        || full[pkg_len] != '.') {
        return NULL;
    }
    return pycc_pkg_member(full + pkg_len + 1);
}

/* `importlib.machinery.ModuleSpec`. */
static PyObject *pycc_pkg_spec_type(void)
{
    PyObject *machinery = PyImport_ImportModule("importlib.machinery");
    PyObject *spec_type;

    if (machinery == NULL) {
        return NULL;
    }
    spec_type = PyObject_GetAttrString(machinery, "ModuleSpec");
    Py_DECREF(machinery);
    return spec_type;
}

/*
 * `find_spec(fullname, path=None, target=None)`: a spec for a compiled
 * module of the package -- origin the path its own extension would have,
 * `has_location` so importlib sets `__file__`, and for a package its
 * directory as the search location -- else None.
 */
static PyObject *pycc_pkg_find_spec(PyObject *self, PyObject *const *args, Py_ssize_t nargs,
                                    PyObject *kwnames)
{
    const PyccPkgMember *member;
    PyObject *rel = NULL, *parts = NULL, *sep = NULL, *dot = NULL, *dir = NULL, *origin = NULL;
    PyObject *spec_type = NULL, *spec = NULL, *call_args = NULL, *kwargs = NULL;
    PyObject *locations = NULL;

    if (nargs < 1) {
        PyErr_SetString(PyExc_TypeError, "find_spec() missing required argument 'fullname'");
        return NULL;
    }
    (void)kwnames;
    member = pycc_pkg_lookup(args[0]);
    if (member == NULL) {
        Py_RETURN_NONE;
    }
    rel = PyUnicode_FromString(member->name);
    sep = PyUnicode_FromString(PYCC_PKG_SEP);
    dot = PyUnicode_FromString(".");
    if (rel == NULL || sep == NULL || dot == NULL) {
        goto done;
    }
    parts = PyUnicode_Split(rel, dot, -1);
    if (parts == NULL) {
        goto done;
    }
    /* `<pkgdir>/sub/mod`, or `<pkgdir>/sub` for a package. */
    if (PyList_Insert(parts, 0, pycc_pkg_dir) != 0) {
        goto done;
    }
    dir = PyUnicode_Join(sep, parts);
    if (dir == NULL) {
        goto done;
    }
    origin = member->is_package ? PyUnicode_FromFormat("%U" PYCC_PKG_SEP "__init__%U", dir, pycc_pkg_suffix)
                                : PyUnicode_FromFormat("%U%U", dir, pycc_pkg_suffix);
    spec_type = pycc_pkg_spec_type();
    call_args = PyTuple_Pack(2, args[0], self);
    kwargs = Py_BuildValue("{sOsO}", "origin", origin == NULL ? Py_None : origin, "is_package",
                           member->is_package ? Py_True : Py_False);
    if (origin == NULL || spec_type == NULL || call_args == NULL || kwargs == NULL) {
        goto done;
    }
    spec = PyObject_Call(spec_type, call_args, kwargs);
    if (spec == NULL) {
        goto done;
    }
    if (PyObject_SetAttrString(spec, "has_location", Py_True) != 0) {
        Py_CLEAR(spec);
        goto done;
    }
    if (member->is_package) {
        locations = PyList_New(1);
        if (locations == NULL) {
            Py_CLEAR(spec);
            goto done;
        }
        PyList_SetItem(locations, 0, Py_NewRef(dir));
        if (PyObject_SetAttrString(spec, "submodule_search_locations", locations) != 0) {
            Py_CLEAR(spec);
        }
    }
done:
    Py_XDECREF(rel);
    Py_XDECREF(parts);
    Py_XDECREF(sep);
    Py_XDECREF(dot);
    Py_XDECREF(dir);
    Py_XDECREF(origin);
    Py_XDECREF(spec_type);
    Py_XDECREF(call_args);
    Py_XDECREF(kwargs);
    Py_XDECREF(locations);
    return spec;
}

/* The member `obj`'s name (a spec's or a module's `__name__`) names, or
 * NULL with an `ImportError` set. */
static const PyccPkgMember *pycc_pkg_member_of(PyObject *obj)
{
    PyObject *name = PyObject_GetAttrString(obj, "name");
    const PyccPkgMember *member;

    if (name == NULL) {
        PyErr_Clear();
        name = PyObject_GetAttrString(obj, "__name__");
    }
    if (name == NULL) {
        return NULL;
    }
    member = pycc_pkg_lookup(name);
    if (member == NULL) {
        PyErr_Format(PyExc_ImportError, "%U is not a compiled module of this package", name);
    }
    Py_DECREF(name);
    return member;
}

/* `create_module(spec)`: the module object of the member, from its own
 * definition. */
static PyObject *pycc_pkg_create_module(PyObject *self, PyObject *spec)
{
    const PyccPkgMember *member = pycc_pkg_member_of(spec);

    (void)self;
    if (member == NULL) {
        return NULL;
    }
    return PyModule_FromDefAndSpec(member->def(), spec);
}

/* `exec_module(module)`: runs the member's body on `module` (its exec
 * slot), on first import and on `importlib.reload`. */
static PyObject *pycc_pkg_exec_module(PyObject *self, PyObject *module)
{
    PyObject *spec;
    const PyccPkgMember *member;

    (void)self;
    spec = PyObject_GetAttrString(module, "__spec__");
    if (spec == NULL) {
        return NULL;
    }
    member = pycc_pkg_member_of(spec);
    Py_DECREF(spec);
    if (member == NULL || PyModule_ExecDef(module, member->def()) != 0) {
        return NULL;
    }
    Py_RETURN_NONE;
}

/*
 * `get_resource_reader(fullname)`: `importlib.resources`' reader of a
 * compiled module, the files of its directory, as a source module's
 * `FileReader` reads them (its `path` the module's origin).
 */
static PyObject *pycc_pkg_get_resource_reader(PyObject *self, PyObject *fullname)
{
    const PyccPkgMember *member = pycc_pkg_lookup(fullname);
    PyObject *spec, *origin, *types, *ns, *readers, *reader;

    if (member == NULL) {
        Py_RETURN_NONE;
    }
    spec = pycc_pkg_find_spec(self, &fullname, 1, NULL);
    if (spec == NULL || spec == Py_None) {
        return spec;
    }
    origin = PyObject_GetAttrString(spec, "origin");
    Py_DECREF(spec);
    if (origin == NULL) {
        return NULL;
    }
    types = PyImport_ImportModule("types");
    ns = types == NULL ? NULL : PyObject_CallMethod(types, "SimpleNamespace", NULL);
    Py_XDECREF(types);
    if (ns == NULL || PyObject_SetAttrString(ns, "path", origin) != 0) {
        Py_XDECREF(ns);
        Py_DECREF(origin);
        return NULL;
    }
    Py_DECREF(origin);
    readers = PyImport_ImportModule("importlib.resources.readers");
    reader = readers == NULL ? NULL : PyObject_CallMethod(readers, "FileReader", "O", ns);
    Py_XDECREF(readers);
    Py_DECREF(ns);
    return reader;
}

static PyMethodDef pycc_pkg_finder_methods[] = {
    {"get_resource_reader", pycc_pkg_get_resource_reader, METH_O, NULL},
    {"find_spec", (PyCFunction)(void (*)(void))pycc_pkg_find_spec, METH_FASTCALL | METH_KEYWORDS,
     NULL},
    {"create_module", pycc_pkg_create_module, METH_O, NULL},
    {"exec_module", pycc_pkg_exec_module, METH_O, NULL},
    {NULL, NULL, 0, NULL},
};

static PyType_Slot pycc_pkg_finder_slots[] = {
    {Py_tp_methods, pycc_pkg_finder_methods},
    {0, NULL},
};

static PyType_Spec pycc_pkg_finder_spec = {
    PYCC_PKG_NAME_STR "._PyccFinder",
    0,
    0,
    Py_TPFLAGS_DEFAULT | Py_TPFLAGS_DISALLOW_INSTANTIATION | Py_TPFLAGS_IMMUTABLETYPE,
    pycc_pkg_finder_slots,
};

/*
 * Records the package's name, directory and suffix from `module` (set by
 * importlib before exec) and puts the finder first on `sys.meta_path`,
 * once. Returns 0, or -1 with an exception set.
 */
static int pycc_pkg_install(PyObject *module)
{
    PyObject *name, *file, *os_path, *dir, *base, *meta_path, *suffix;
    Py_ssize_t base_len;
    int found;

    name = PyModule_GetNameObject(module);
    file = PyModule_GetFilenameObject(module);
    if (name == NULL || file == NULL) {
        Py_XDECREF(name);
        Py_XDECREF(file);
        return -1;
    }
    os_path = PyImport_ImportModule("os.path");
    dir = os_path == NULL ? NULL : PyObject_CallMethod(os_path, "dirname", "O", file);
    base = os_path == NULL ? NULL : PyObject_CallMethod(os_path, "basename", "O", file);
    Py_XDECREF(os_path);
    Py_DECREF(file);
    if (dir == NULL || base == NULL) {
        Py_DECREF(name);
        Py_XDECREF(dir);
        Py_XDECREF(base);
        return -1;
    }
    /* `__init__.abi3.so` -> `.abi3.so`. */
    base_len = PyUnicode_GetLength(base);
    suffix = PyUnicode_Substring(base, 8, base_len < 8 ? 8 : base_len);
    Py_DECREF(base);
    if (suffix == NULL) {
        Py_DECREF(name);
        Py_DECREF(dir);
        return -1;
    }
    Py_XDECREF(pycc_pkg_name);
    Py_XDECREF(pycc_pkg_dir);
    Py_XDECREF(pycc_pkg_suffix);
    pycc_pkg_name = name;
    pycc_pkg_dir = dir;
    pycc_pkg_suffix = suffix;
    if (pycc_pkg_finder == NULL) {
        PyObject *type = PyType_FromSpec(&pycc_pkg_finder_spec);
        allocfunc tp_alloc;

        if (type == NULL) {
            return -1;
        }
        tp_alloc = (allocfunc)PyType_GetSlot((PyTypeObject *)type, Py_tp_alloc);
        pycc_pkg_finder = tp_alloc((PyTypeObject *)type, 0);
        Py_DECREF(type);
        if (pycc_pkg_finder == NULL) {
            return -1;
        }
    }
    meta_path = PySys_GetObject("meta_path");
    if (meta_path == NULL || !PyList_Check(meta_path)) {
        PyErr_SetString(PyExc_ImportError, "sys.meta_path is not a list");
        return -1;
    }
    found = PySequence_Contains(meta_path, pycc_pkg_finder);
    if (found < 0) {
        return -1;
    }
    if (!found && PyList_Insert(meta_path, 0, pycc_pkg_finder) != 0) {
        return -1;
    }
    return 0;
}

/* The package module's exec: the finder first, so the package's own body
 * imports its compiled submodules through it, then that body. */
static int pycc_pkg_exec(PyObject *module)
{
    if (pycc_pkg_install(module) != 0) {
        return -1;
    }
    return PyModule_ExecDef(module, pycc_pkg_members[0].def());
}

static PyModuleDef_Slot pycc_pkg_slots[] = {
    {Py_mod_exec, (void *)pycc_pkg_exec},
    {Py_mod_multiple_interpreters, Py_MOD_MULTIPLE_INTERPRETERS_NOT_SUPPORTED},
    {0, NULL},
};

static struct PyModuleDef pycc_pkg_def = {
    PyModuleDef_HEAD_INIT,
    PYCC_PKG_NAME_STR,
    NULL,
    0,
    NULL,
    pycc_pkg_slots,
    NULL,
    NULL,
    NULL,
};

#define PYCC_PKG_CONCAT_(a, b) a##b
#define PYCC_PKG_CONCAT(a, b) PYCC_PKG_CONCAT_(a, b)

PyMODINIT_FUNC PYCC_PKG_CONCAT(PyInit_, PYCC_PKG_NAME)(void)
{
    /* As a module of its own refuses one (`module_init.c`). */
    if (strstr(Py_GetVersion(), "free-threading build") != NULL) {
        PyErr_SetString(PyExc_ImportError,
                        PYCC_PKG_NAME_STR " was built for a GIL-enabled CPython "
                        "(stable ABI); this interpreter is a free-threaded build, which is "
                        "not supported");
        return NULL;
    }
    /* The package's docstring is its `__init__`'s. */
    pycc_pkg_def.m_doc = pycc_pkg_members[0].def()->m_doc;
    return PyModuleDef_Init(&pycc_pkg_def);
}
