//! The shim as two translation units (v0.8 accept 4): a *runtime* unit, the
//! same text for every module, and a small *module* unit holding what the
//! module's generated companion ([`super::EXPORTS_INC_NAME`]) adds and its
//! `PyInit_` entry point (`module_init.c`).
//!
//! Compiling the whole 8,000-line shim at `-O2` for every module used to be
//! most of an `--ext` build of a small module (about a second each, 38 times
//! for a package of 38 modules). The runtime unit depends on nothing but the
//! fixed sources, the compile flags and the CPython headers, so its object is
//! compiled once and reused from the build cache
//! (`crate::build_pipeline::c_objects`); only the module unit is compiled per
//! module.
//!
//! The fixed sources are written as one translation unit, their file-scope
//! definitions `static`. Each unit is derived from them mechanically:
//!
//! * every column-0 `static` becomes `PYCC_SHIM` -- hidden visibility, so a
//!   definition is shared by the two units of one artifact and by no other
//!   artifact (each still carries its own copy of every file-scope variable);
//! * the module unit opens with [`declarations`] of the runtime unit: every
//!   function definition as its prototype, every variable definition as an
//!   `extern` declaration, the types and macros as written;
//! * what differs per module -- its name, the companion's class tables, its
//!   carrier types, forwarder slots and home module -- reaches the runtime
//!   unit as the module's record (`PyccExtModule`), which the module unit
//!   defines (`module_ctx.c`) and passes to the runtime functions that need
//!   it, so one runtime unit serves every module of a package's extension.
//!
//! The fixed sources keep one style this relies on: a function body opens
//! with a `{` line and closes with a `}` line, both at column 0, and nothing
//! else does.

use std::sync::OnceLock;

/// The fixed shim without `module_init.c` (the module unit's), in
/// translation-unit order, with `instances.c`'s include of the companion.
const FIXED_C: &str = concat!(
    include_str!("../ext/module/bridge.c"),
    include_str!("../ext/module/frames.c"),
    include_str!("../ext/module/boundary.c"),
    include_str!("../ext/module/global_sync.c"),
    include_str!("../ext/module/import_io.c"),
    include_str!("../ext/module/object_unpack.c"),
    include_str!("../ext/module/attr_cache.c"),
    include_str!("../ext/module/object_ops.c"),
    include_str!("../ext/module/object_index.c"),
    include_str!("../ext/module/object_convert.c"),
    include_str!("../ext/module/object_text.c"),
    include_str!("../ext/module/object_stdlib.c"),
    include_str!("../ext/module/object_intrinsics.c"),
    include_str!("../ext/module/object_except.c"),
    include_str!("../ext/module/object_closure.c"),
    include_str!("../ext/module/ndarray.c"),
    include_str!("../ext/module/bytearray.c"),
    include_str!("../ext/module/instances.c"),
    include_str!("../ext/module/forward.c"),
    include_str!("../ext/module/buffers.c"),
    include_str!("../ext/pycc_ext_object_ops.c"),
);

const MODULE_INIT_C: &str = include_str!("../ext/module/module_init.c");

/// The module unit's entry points into the runtime unit over the module's
/// record (`PyccExtModule`): their declarations, ahead of the companion that
/// calls them, and the record with their definitions, after it.
const MODULE_CTX_HEAD_C: &str = include_str!("../ext/module/module_ctx_head.c");
const MODULE_CTX_C: &str = include_str!("../ext/module/module_ctx.c");

/// The companion's include in [`FIXED_C`]: the module unit's, not the
/// runtime unit's.
const INCLUDE_COMPANION: &str = "#include \"pycc_ext_exports.inc\"\n";

/// The linkage every file-scope definition of either unit gets, and the
/// module unit's entry points LLVM-generated code calls (`PYCC_ENTRY`).
const LINKAGE: &str = "/* Generated by pycc from the --ext shim's fixed sources (src/ext/module/). */\n\
#if defined(_WIN32)\n\
#define PYCC_SHIM\n\
#define PYCC_ENTRY\n\
#else\n\
#define PYCC_SHIM __attribute__((visibility(\"hidden\")))\n\
#define PYCC_ENTRY __attribute__((visibility(\"hidden\")))\n\
#endif\n";

/// A module of a package built whole (`PYCC_EXT_PACKAGE_MEMBER`, v0.8): the
/// module unit first reads its symbol names (`pycc_ext_member.h`, written
/// beside it: every name it shares with the module's LLVM object, prefixed
/// per module), and its own definitions are `static` once the runtime
/// unit's declarations are behind it, so the modules of one extension never
/// share a symbol but the runtime unit's.
const MEMBER_HEADER: &str =
    "#ifdef PYCC_EXT_PACKAGE_MEMBER\n#include \"pycc_ext_member.h\"\n#endif\n";
const MEMBER_STATIC: &str =
    "#ifdef PYCC_EXT_PACKAGE_MEMBER\n#undef PYCC_SHIM\n#define PYCC_SHIM static\n#endif\n";

/// `text` with every column-0 `static` (a file-scope definition or
/// declaration) made [`LINKAGE`]'s `PYCC_SHIM`.
pub(crate) fn relink(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + text.len() / 32);
    for line in text.split_inclusive('\n') {
        match line.strip_prefix("static ") {
            Some(rest) => {
                out.push_str("PYCC_SHIM ");
                out.push_str(rest);
            }
            None => out.push_str(line),
        }
    }
    out
}

/// What a unit using the definitions of `text` (relinked) needs to see:
/// `text` with each function body replaced by the `;` ending its
/// prototype, and each variable definition by an `extern` declaration.
pub(crate) fn declarations(text: &str) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut lines = text.lines();
    while let Some(line) = lines.next() {
        if line == "{" {
            // A function body: its signature, above, becomes a prototype.
            if let Some(signature) = out.iter_mut().rev().find(|l| !l.trim().is_empty()) {
                signature.push(';');
            }
            for body in lines.by_ref() {
                if body == "}" {
                    break;
                }
            }
            continue;
        }
        if let Some(declared) = variable_declaration(line) {
            out.push(declared);
            // A multi-line initializer runs to its own `};`.
            if line.contains('=') && !line.trim_end().ends_with(';') {
                for initializer in lines.by_ref() {
                    if initializer.starts_with("};") {
                        break;
                    }
                }
            }
            continue;
        }
        out.push(line.to_string());
    }
    let mut joined = out.join("\n");
    joined.push('\n');
    joined
}

/// The `extern` declaration a column-0 file-scope variable definition of
/// `line` stands for, or `None` when `line` is anything else (a function's
/// signature, a type, a preprocessor line, a comment, a declaration).
fn variable_declaration(line: &str) -> Option<String> {
    let starts_definition = line
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_');
    if !starts_definition
        || line.starts_with("typedef")
        || line.starts_with("extern")
        || line.starts_with("struct")
        || line.starts_with("PyMODINIT_FUNC")
    {
        return None;
    }
    // A function's signature or prototype has a parameter list before any
    // initializer (a function-pointer variable is not written in the
    // fixed sources).
    let head = line
        .split_once('=')
        .map_or(line, |(head, _)| head)
        .trim_end();
    if head.contains('(') {
        return None;
    }
    // A multi-line `struct {` member list is declared as written, `extern`
    // first.
    if !line.contains('=') && head.ends_with('{') {
        return Some(format!("extern {line}"));
    }
    let head = head.strip_suffix(';').unwrap_or(head);
    if !line.contains('=') && !line.trim_end().ends_with(';') {
        return None;
    }
    Some(format!("extern {head};"))
}

/// `text` with `\n` line ends: a checkout with `core.autocrlf` (Windows)
/// gives the fixed sources `\r\n` ones, which [`INCLUDE_COMPANION`] and the
/// column-0 matching of [`declarations`] would not see.
fn unix_lines(text: &str) -> String {
    text.replace("\r\n", "\n")
}

/// The runtime unit: the same text for every module of one pycc version.
pub(crate) fn runtime_unit() -> &'static str {
    static UNIT: OnceLock<String> = OnceLock::new();
    UNIT.get_or_init(|| {
        let fixed = unix_lines(FIXED_C).replace(INCLUDE_COMPANION, "");
        format!("{LINKAGE}{}", relink(&fixed))
    })
}

/// The module unit: the runtime unit's [`declarations`], the declarations
/// of the module's entry points (`module_ctx_head.c`), the companion
/// (written beside it, relinked by [`relink`]), the module's record and
/// entry points (`module_ctx.c`), and `module_init.c`.
pub(crate) fn module_unit() -> &'static str {
    static UNIT: OnceLock<String> = OnceLock::new();
    UNIT.get_or_init(|| {
        let fixed = unix_lines(FIXED_C).replace(INCLUDE_COMPANION, "");
        format!(
            "{LINKAGE}{MEMBER_HEADER}{}\n{MEMBER_STATIC}{}\n{INCLUDE_COMPANION}\n{}\n{}",
            declarations(&relink(&fixed)),
            relink(&unix_lines(MODULE_CTX_HEAD_C)),
            relink(&unix_lines(MODULE_CTX_C)),
            relink(&unix_lines(MODULE_INIT_C))
        )
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn relink_rewrites_only_column_zero_statics() {
        let text = "static int f(void)\n{\n    static int x = 0;\n    return x;\n}\nint g;\n";
        assert_eq!(
            relink(text),
            "PYCC_SHIM int f(void)\n{\n    static int x = 0;\n    return x;\n}\nint g;\n"
        );
    }

    #[test]
    fn declarations_keep_prototypes_types_and_macros_and_declare_variables() {
        let text = "#define N 3\ntypedef struct {\n    int a;\n} T;\n\
                    PYCC_SHIM int f(int a,\n                int b)\n{\n    return a;\n}\n\
                    PYCC_SHIM PyObject *x = NULL;\nPyObject *y[4] = {NULL, NULL, NULL, NULL};\n\
                    PYCC_SHIM PyType_Slot s[] = {\n    {0, NULL},\n};\nPYCC_SHIM struct {\n    \
                    int k;\n} cache[8];\nPYCC_SHIM int g(void);\n";
        assert_eq!(
            declarations(text),
            "#define N 3\ntypedef struct {\n    int a;\n} T;\n\
             PYCC_SHIM int f(int a,\n                int b);\n\
             extern PYCC_SHIM PyObject *x;\nextern PyObject *y[4];\n\
             extern PYCC_SHIM PyType_Slot s[];\nextern PYCC_SHIM struct {\n    \
             int k;\n} cache[8];\nPYCC_SHIM int g(void);\n"
        );
    }

    #[test]
    fn sources_with_windows_line_ends_split_the_same() {
        let crlf = "#include \"pycc_ext_exports.inc\"\r\nstatic int f(void)\r\n{\r\n    \
                    return 0;\r\n}\r\n";
        let fixed = unix_lines(crlf).replace(INCLUDE_COMPANION, "");
        assert_eq!(fixed, "static int f(void)\n{\n    return 0;\n}\n");
        assert_eq!(declarations(&relink(&fixed)), "PYCC_SHIM int f(void);\n");
    }

    #[test]
    fn the_fixed_sources_keep_the_style_the_split_relies_on() {
        // Every body opens and closes at column 0, once each.
        let opens = FIXED_C.lines().filter(|l| *l == "{").count();
        let closes = FIXED_C.lines().filter(|l| *l == "}").count();
        assert_eq!(opens, closes);
        // No `static` function-local variable would be relinked (they are
        // indented), and the companion is included exactly once.
        assert_eq!(unix_lines(FIXED_C).matches(INCLUDE_COMPANION).count(), 1);
        assert!(!runtime_unit().contains(INCLUDE_COMPANION));
        assert_eq!(module_unit().matches(INCLUDE_COMPANION).count(), 1);
        assert!(!runtime_unit().lines().any(|l| l.starts_with("static ")));
    }
}
