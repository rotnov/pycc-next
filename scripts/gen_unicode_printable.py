#!/usr/bin/env python3
"""Generates crates/pycc_rt/src/unicode_printable.rs from CPython's own data.

`repr()` of a `str` escapes every character `str.isprintable()` rejects: the
Unicode categories Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs, except the ASCII space.
The table lists those characters as sorted, merged inclusive ranges, taken
from the running CPython (the oracle, 3.13: its `unicodedata` version is
recorded in the file).

    python3 scripts/gen_unicode_printable.py            # rewrite the file
    python3 scripts/gen_unicode_printable.py --check    # exit 1 if stale
"""

import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/pycc_rt/src/unicode_printable.rs"


def ranges() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if chr(cp).isprintable():
            continue
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def render() -> str:
    rows = ranges()
    lines = [
        "//! Characters `str.isprintable()` rejects, which `repr()` of a `str`",
        "//! escapes: Unicode categories Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs (except",
        "//! the ASCII space), as sorted inclusive ranges.",
        "//!",
        f"//! Generated by `scripts/gen_unicode_printable.py` from CPython {sys.version_info[0]}.{sys.version_info[1]}",
        f"//! (Unicode {unicodedata.unidata_version}); do not edit by hand.",
        "",
        "/// Whether CPython's `str.isprintable()` holds for `c`.",
        "pub(crate) fn is_printable(c: char) -> bool {",
        "    let cp = c as u32;",
        "    NON_PRINTABLE",
        "        .binary_search_by(|&(lo, hi)| {",
        "            if hi < cp {",
        "                std::cmp::Ordering::Less",
        "            } else if lo > cp {",
        "                std::cmp::Ordering::Greater",
        "            } else {",
        "                std::cmp::Ordering::Equal",
        "            }",
        "        })",
        "        .is_err()",
        "}",
        "",
        f"static NON_PRINTABLE: [(u32, u32); {len(rows)}] = [",
    ]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in rows]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT} is stale: run python3 scripts/gen_unicode_printable.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
