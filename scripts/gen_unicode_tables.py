#!/usr/bin/env python3
"""Generates crates/pycc_rt/src/unicode_tables.rs from CPython's own data.

Two tables, taken from the running CPython (the oracle, 3.13; its
`unicodedata` version is recorded in the file):

- the characters `str.isprintable()` rejects (categories Cc, Cf, Cs, Co,
  Cn, Zl, Zp and Zs, except the ASCII space), which `repr()` of a `str`
  escapes, as sorted, merged inclusive ranges;
- the zero of every run of Unicode decimal digits (category Nd, ten in a
  row), which `int()` and `float()` read as ASCII digits.

    python3 scripts/gen_unicode_tables.py            # rewrite the file
    python3 scripts/gen_unicode_tables.py --check    # exit 1 if stale
"""

import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/pycc_rt/src/unicode_tables.rs"


def non_printable() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if chr(cp).isprintable():
            continue
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def decimal_zeros() -> list[int]:
    zeros = [cp for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) == 0]
    for z in zeros:
        assert all(unicodedata.decimal(chr(z + i), None) == i for i in range(10)), hex(z)
    count = sum(1 for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) is not None)
    assert count == 10 * len(zeros)
    return zeros


def render() -> str:
    rows = non_printable()
    zeros = decimal_zeros()
    lines = [
        "//! Unicode tables CPython's `str` behavior needs, generated from its",
        "//! `unicodedata`: the characters `str.isprintable()` rejects (categories",
        "//! Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs, except the ASCII space), which",
        "//! `repr()` of a `str` escapes, and the Unicode decimal digits `int()` and",
        "//! `float()` read.",
        "//!",
        "//! Generated by `scripts/gen_unicode_tables.py` from CPython "
        f"{sys.version_info[0]}.{sys.version_info[1]}",
        f"//! (Unicode {unicodedata.unidata_version}); do not edit by hand.",
        "",
        "/// Whether CPython's `str.isprintable()` holds for `c`.",
        "pub(crate) fn is_printable(c: char) -> bool {",
        "    let cp = c as u32;",
        "    NON_PRINTABLE",
        "        .binary_search_by(|&(lo, hi)| {",
        "            if hi < cp {",
        "                std::cmp::Ordering::Less",
        "            } else if lo > cp {",
        "                std::cmp::Ordering::Greater",
        "            } else {",
        "                std::cmp::Ordering::Equal",
        "            }",
        "        })",
        "        .is_err()",
        "}",
        "",
        "/// The value of `c` as a Unicode decimal digit (`unicodedata.decimal`).",
        "pub(crate) fn decimal_value(c: char) -> Option<u32> {",
        "    let cp = c as u32;",
        "    let at = DECIMAL_ZEROS.partition_point(|&zero| zero <= cp);",
        "    let zero = *DECIMAL_ZEROS.get(at.checked_sub(1)?)?;",
        "    (cp - zero < 10).then_some(cp - zero)",
        "}",
        "",
        f"static NON_PRINTABLE: [(u32, u32); {len(rows)}] = [",
    ]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in rows]
    lines.append("];")
    lines.append("")
    lines.append(f"static DECIMAL_ZEROS: [u32; {len(zeros)}] = [")
    lines += [f"    0x{z:X}," for z in zeros]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT} is stale: run python3 scripts/gen_unicode_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
